#!/usr/bin/env python3
"""Regenerate every table and figure from results/.

    python scripts/make_paper_assets.py --results results --out paper

Tables are LaTeX, figures are vector PDF, and neither is ever edited by hand.
A cell whose run did not happen is written as ``TODO``; it is never filled
with a plausible value, and the script prints a summary of how many TODOs
remain so that an incomplete table cannot be mistaken for a complete one.

Every claim of "better" is looked up in results/significance.json. A
comparison absent from that file is rendered without a significance marker,
not with an optimistic one.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402

from flowconx.analysis.aggregate import aggregate  # noqa: E402

TODO = r"\textsc{todo}"

# Colourblind-safe (Okabe-Ito). Used for every figure so the paper reads as
# one document rather than as a collection of default matplotlib styles.
PALETTE = ["#0072B2", "#D55E00", "#009E73", "#CC79A7", "#E69F00", "#56B4E9", "#F0E442", "#000000"]


def latex_escape(text: str) -> str:
    for old, new in (("_", r"\_"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#")):
        text = text.replace(old, new)
    return text


def fmt(mean: Optional[float], std: Optional[float] = None, places: int = 3) -> str:
    if mean is None or not np.isfinite(mean):
        return TODO
    if std is None or not np.isfinite(std):
        return f"{mean:.{places}f}"
    return f"{mean:.{places}f} $\\pm$ {std:.{places}f}"


def table_wrapper(body: str, caption: str, label: str, columns: str) -> str:
    return "\n".join(
        [
            "% Generated by scripts/make_paper_assets.py. Do not edit by hand.",
            r"\begin{table}[t]",
            r"\centering",
            r"\small",
            f"\\begin{{tabular}}{{{columns}}}",
            r"\toprule",
            body,
            r"\bottomrule",
            r"\end{tabular}",
            f"\\caption{{{caption}}}",
            f"\\label{{{label}}}",
            r"\end{table}",
            "",
        ]
    )


def _cell(group: Optional[Dict[str, Any]], head: str, metric: str = "macro_f1") -> str:
    """A table cell, or TODO when the run behind it has not happened."""
    if not group:
        return TODO
    stats = group.get("heads", {}).get(head, {}).get(metric)
    if not stats:
        return TODO
    return fmt(stats.get("mean"), stats.get("std"))


def _index(groups: Sequence[Dict[str, Any]]) -> Dict[Tuple[str, str, str], Dict[str, Any]]:
    return {(g["experiment"], g["dataset"], g["split"]): g for g in groups}


# --------------------------------------------------------------------------
# Table 1: split protocol contrast. The measurement contribution.
# --------------------------------------------------------------------------

SPLIT_ORDER = ["random_flow", "session_disjoint", "temporal", "server_disjoint"]
SPLIT_LABEL = {
    "random_flow": "Random flow",
    "session_disjoint": "Session-disjoint",
    "temporal": "Temporal",
    "server_disjoint": "Server-disjoint",
}


def table_split_contrast(index, datasets: Sequence[str], audit: Dict[str, Any]) -> str:
    """How much the field's usual protocol inflates a published-style number."""
    rows: List[str] = []
    header = ["Split protocol"] + [latex_escape(d) for d in datasets]
    rows.append(" & ".join(header) + r" \\")
    rows.append(r"\midrule")
    rows.append(r"\multicolumn{%d}{l}{\emph{FlowCon-X (prototype head)}} \\" % (len(datasets) + 1))
    for split in SPLIT_ORDER:
        cells = []
        for dataset in datasets:
            group = None
            for (experiment, ds, sp), candidate in index.items():
                if ds == dataset and sp == split and experiment.startswith("flowconx_"):
                    group = candidate
                    break
            cells.append(_cell(group, "prototype") if group else TODO)
        rows.append(f"{SPLIT_LABEL[split]} & " + " & ".join(cells) + r" \\")

    if audit:
        rows.append(r"\midrule")
        rows.append(r"\multicolumn{%d}{l}{\emph{AppScanner (2016), identical splits}} \\" % (len(datasets) + 1))
        for split in SPLIT_ORDER:
            cells = []
            for dataset in datasets:
                value = (
                    audit.get(dataset, {})
                    .get("splits", {})
                    .get(split, {})
                    .get("baselines", {})
                    .get("appscanner", {})
                    .get("macro_f1")
                )
                cells.append(fmt(value) if isinstance(value, (int, float)) else TODO)
            rows.append(f"{SPLIT_LABEL[split]} & " + " & ".join(cells) + r" \\")

    return table_wrapper(
        "\n".join(rows),
        caption=(
            "Macro-F1 under four split protocols. The random-flow row is the field's usual protocol and "
            "is reported only as a contrast: correlated flows from one capture session appear on both "
            "sides of it. The gap between it and the session-disjoint row is the inflation that protocol "
            "produces, and it applies to a 2016 statistical baseline as much as to our model."
        ),
        label="tab:split-contrast",
        columns="l" + "c" * len(datasets),
    )


# --------------------------------------------------------------------------
# Table 2: main comparison against every baseline we could run.
# --------------------------------------------------------------------------

BASELINE_TIERS = [
    ("Identifier shortcuts", ["port_only", "sni_only", "server_ip_only", "server_asn_only", "protocol_only"]),
    ("Classical statistical", ["five_stat", "size_histogram", "cumul", "appscanner", "kfp"]),
    ("Deep, non-pretrained", ["deeppacket_cnn", "fsnet", "lstm_attention", "mlp_stats"]),
]
PRETTY = {
    "port_only": "Destination port only",
    "sni_only": "SNI string only",
    "server_ip_only": "Server IP / prefix only",
    "server_asn_only": "Server AS only",
    "protocol_only": "Transport protocol only",
    "five_stat": "5 flow statistics (RF)",
    "size_histogram": "Packet-size histogram (XGB)",
    "cumul": "CUMUL",
    "appscanner": "AppScanner",
    "kfp": "$k$-fingerprinting",
    "deeppacket_cnn": "DeepPacket-style CNN",
    "fsnet": "FS-Net",
    "lstm_attention": "Bi-LSTM + attention",
    "mlp_stats": "Flow-statistics MLP",
    "majority_class": "Majority class",
}


def table_main_comparison(index, audit, dataset: str, split: str) -> str:
    rows: List[str] = [r"Method & Macro-F1 & Balanced acc. & Params \\", r"\midrule"]
    audit_split = audit.get(dataset, {}).get("splits", {}).get(split, {}).get("baselines", {})

    floor = audit_split.get("majority_class", {})
    rows.append(
        f"{PRETTY['majority_class']} & {fmt(floor.get('macro_f1'))} & "
        f"{fmt(floor.get('balanced_accuracy'))} & --- \\\\"
    )
    for tier, families in BASELINE_TIERS:
        rows.append(r"\midrule")
        rows.append(rf"\multicolumn{{4}}{{l}}{{\emph{{{tier}}}}} \\")
        for family in families:
            if family in audit_split:
                entry = audit_split[family]
                rows.append(
                    f"{PRETTY.get(family, latex_escape(family))} & {fmt(entry.get('macro_f1'))} & "
                    f"{fmt(entry.get('balanced_accuracy'))} & --- \\\\"
                )
                continue
            group = index.get((f"baseline_{family}", dataset, split))
            if group is None:
                rows.append(f"{PRETTY.get(family, latex_escape(family))} & {TODO} & {TODO} & {TODO} \\\\")
                continue
            params = group.get("extras", {}).get("n_parameters", {}).get("mean")
            rows.append(
                f"{PRETTY.get(family, latex_escape(family))} & {_cell(group, 'softmax')} & "
                f"{_cell(group, 'softmax', 'balanced_accuracy')} & "
                f"{int(params):,} \\\\".replace(",", r"\,")
                if params
                else f"{PRETTY.get(family, latex_escape(family))} & {_cell(group, 'softmax')} & "
                f"{_cell(group, 'softmax', 'balanced_accuracy')} & {TODO} \\\\"
            )

    rows.append(r"\midrule")
    ours = index.get(("flowconx_main", dataset, split))
    params = (ours or {}).get("extras", {}).get("n_parameters", {}).get("mean")
    rows.append(
        rf"\textbf{{FlowCon-X}} & \textbf{{{_cell(ours, 'prototype')}}} & "
        rf"{_cell(ours, 'prototype', 'balanced_accuracy')} & "
        + (f"{int(params):,}".replace(",", r"\,") if params else TODO)
        + r" \\"
    )
    return table_wrapper(
        "\n".join(rows),
        caption=(
            f"Main comparison on {latex_escape(dataset)} under the {SPLIT_LABEL.get(split, split).lower()} "
            "protocol, mean $\\pm$ std over seeds, every method on the identical committed splits. "
            "Identifier shortcuts are included deliberately: if one of them approaches the rest, the "
            "benchmark is not measuring traffic analysis. Pre-trained byte-level transformers "
            "(ET-BERT, YaTC, CLE-TFE) are absent because our records retain no payload; see "
            r"\texttt{flowconx/baselines/WHY\_NOT\_RUN.md}."
        ),
        label=f"tab:main-{dataset}",
        columns="lccc",
    )


