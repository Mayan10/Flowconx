def table_cost(index, dataset: str, split: str) -> str:
    rows: List[str] = [
        r"Method & p50 (ms) & p95 (ms) & p99 (ms) & Flows/s & Params & Size (MB) & New class \\",
        r"\midrule",
    ]
    candidates = [("flowconx_main", "FlowCon-X")] + [
        (f"baseline_{name}", PRETTY.get(name, name))
        for name in ("deeppacket_cnn", "fsnet", "lstm_attention", "mlp_stats")
    ]
    for experiment, label in candidates:
        group = index.get((experiment, dataset, split))
        if group is None:
            rows.append(f"{label} & " + " & ".join([TODO] * 7) + r" \\")
            continue
        extras = group.get("extras", {})

        def value(name: str, scale: float = 1.0, places: int = 2) -> str:
            stats = extras.get(name)
            if not stats or not np.isfinite(stats.get("mean", float("nan"))):
                return TODO
            return f"{stats['mean'] * scale:.{places}f}"

        params = extras.get("n_parameters", {}).get("mean")
        # The cost asymmetry the paper's enrollment claim rests on.
        enrollment = r"$k$ fwd passes" if experiment == "flowconx_main" else "fine-tune"
        rows.append(
            f"{label} & {value('latency_p50_ms')} & {value('latency_p95_ms')} & {value('latency_p99_ms')} & "
            f"{value('throughput_flows_per_s', places=0)} & "
            + (f"{int(params):,}".replace(",", r"\,") if params else TODO)
            + f" & {value('model_size_bytes', 1e-6, 1)} & {enrollment} \\\\"
        )
    return table_wrapper(
        "\n".join(rows),
        caption=(
            "Deployment cost, measured on identical hardware. Latency percentiles are end-to-end -- stored "
            "record in, decision out, including feature construction -- at batch size 1, not a mean of the "
            "forward pass alone. The last column is the cost of adding one new application: a prototype "
            "update needs $k$ forward passes, a softmax classifier needs a fine-tuning run."
        ),
        label="tab:cost",
        columns="lccccccc",
    )


