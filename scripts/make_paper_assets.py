def _style():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {
            "figure.figsize": (3.4, 2.4),
            "font.size": 8,
            "axes.labelsize": 8,
            "axes.titlesize": 8,
            "legend.fontsize": 7,
            "xtick.labelsize": 7,
            "ytick.labelsize": 7,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.alpha": 0.25,
            "grid.linewidth": 0.5,
            "lines.linewidth": 1.4,
            "lines.markersize": 3.5,
            "savefig.bbox": "tight",
            "savefig.pad_inches": 0.02,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )
    return plt


def _runs_with(results_root: Path, key: str) -> List[Dict[str, Any]]:
    out = []
    for path in sorted(results_root.rglob("metrics.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        block = payload.get(key)
        if isinstance(block, dict) and block.get("status") == "ok":
            out.append(payload)
    return out


def figure_early_classification(results_root: Path, out_dir: Path) -> Optional[Path]:
    runs = _runs_with(results_root, "early_classification")
    if not runs:
        return None
    plt = _style()
    figure, axis = plt.subplots()
    series: Dict[str, Dict[int, List[float]]] = {}
    for payload in runs:
        label = f"{payload['config']['data']['dataset']}"
        bucket = series.setdefault(label, {})
        for point in payload["early_classification"]["curve"]:
            bucket.setdefault(int(point["observed_packets"]), []).append(float(point["macro_f1"]))
    for i, (label, points) in enumerate(sorted(series.items())):
        budgets = sorted(points)
        means = [float(np.mean(points[b])) for b in budgets]
        stds = [float(np.std(points[b])) for b in budgets]
        axis.errorbar(budgets, means, yerr=stds, marker="o", color=PALETTE[i % len(PALETTE)], label=label, capsize=2)
    axis.set_xlabel("Observed packets")
    axis.set_ylabel("Macro-F1")
    axis.set_xscale("log")
    axis.legend(frameon=False)
    path = out_dir / "early_classification.pdf"
    figure.savefig(path)
    plt.close(figure)
    return path


def figure_enrollment(results_root: Path, out_dir: Path) -> Optional[Path]:
    runs = _runs_with(results_root, "few_shot")
    if not runs:
        return None
    plt = _style()
    figure, axis = plt.subplots()
    points: Dict[int, List[float]] = {}
    for payload in runs:
        for entry in payload["few_shot"].get("service_enrollment", []):
            points.setdefault(int(entry["shots"]), []).append(float(entry["macro_f1_mean"]))
    if not points:
        plt.close(figure)
        return None
    shots = sorted(points)
    axis.errorbar(
        shots,
        [float(np.mean(points[k])) for k in shots],
        yerr=[float(np.std(points[k])) for k in shots],
        marker="o",
        color=PALETTE[0],
        capsize=2,
        label="FlowCon-X (frozen encoder)",
    )
    axis.set_xlabel("Labelled flows per enrolled class")
    axis.set_ylabel("Macro-F1")
    axis.set_xscale("log")
    axis.legend(frameon=False)
    path = out_dir / "enrollment_curve.pdf"
    figure.savefig(path)
    plt.close(figure)
    return path


def figure_robustness(results_root: Path, out_dir: Path) -> Optional[Path]:
    runs = _runs_with(results_root, "robustness")
    if not runs:
        return None
    plt = _style()
    figure, axis = plt.subplots(figsize=(3.4, 2.6))
    rows: Dict[str, List[Tuple[float, float]]] = {}
    for payload in runs:
        for entry in payload["robustness"]["perturbations"]:
            if entry["name"] == "clean":
                continue
            rows.setdefault(entry["name"], []).append(
                (float(entry.get("byte_overhead_ratio", 1.0)), float(entry["macro_f1"]))
            )
    if not rows:
        plt.close(figure)
        return None
    for i, (name, values) in enumerate(sorted(rows.items())):
        overhead = float(np.mean([v[0] for v in values]))
        score = float(np.mean([v[1] for v in values]))
        axis.scatter(overhead, score, color=PALETTE[i % len(PALETTE)], label=name.replace("_", " "), zorder=3)
    axis.set_xlabel("Byte overhead (x baseline)")
    axis.set_ylabel("Macro-F1 under defence")
    axis.legend(frameon=False, ncol=2, fontsize=5.5)
    path = out_dir / "robustness_overhead.pdf"
    figure.savefig(path)
    plt.close(figure)
    return path


def figure_adversarial_tradeoff(results_root: Path, out_dir: Path) -> Optional[Path]:
    points: List[Tuple[float, float, float]] = []
    for path in sorted(results_root.rglob("metrics.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        tradeoff = (payload.get("probes") or {}).get("tradeoff")
        if not tradeoff:
            continue
        points.append(
            (
                float(payload["config"]["loss"]["lambda_adversarial"]),
                float(tradeoff["nuisance_above_majority_mlp"]),
                float(tradeoff["task_macro_f1_mlp"]),
            )
        )
    if len(points) < 2:
        return None
    plt = _style()
    figure, axis = plt.subplots()
    weights = sorted({p[0] for p in points})
    nuisance = [float(np.mean([p[1] for p in points if p[0] == w])) for w in weights]
    task = [float(np.mean([p[2] for p in points if p[0] == w])) for w in weights]
    axis.plot(weights, nuisance, marker="o", color=PALETTE[1], label="Nuisance probe above chance")
    axis.plot(weights, task, marker="s", color=PALETTE[0], label="Task macro-F1")
    axis.set_xlabel(r"Adversarial weight $\lambda_{\mathrm{adv}}$")
    axis.set_ylabel("Score")
    axis.legend(frameon=False)
    path = out_dir / "adversarial_tradeoff.pdf"
    figure.savefig(path)
    plt.close(figure)
    return path


