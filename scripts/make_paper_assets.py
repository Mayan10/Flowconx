SPLIT_ORDER = ["random_flow", "session_disjoint", "temporal", "server_disjoint"]
SPLIT_LABEL = {
    "random_flow": "Random flow",
    "session_disjoint": "Session-disjoint",
    "temporal": "Temporal",
    "server_disjoint": "Server-disjoint",
}

# Which experiment supplies each protocol's row. Explicit, so a new experiment
# whose name happens to share a prefix cannot displace the intended one.
SPLIT_EXPERIMENT = {
    "random_flow": "flowconx_random_contrast",
    "session_disjoint": "flowconx_main",
    "temporal": "flowconx_temporal",
    "server_disjoint": "flowconx_server_disjoint",
}


def table_split_contrast(index, datasets: Sequence[str], audit: Dict[str, Any]) -> str:
    """How much the field's usual protocol inflates a published-style number."""
    rows: List[str] = []
    header = ["Split protocol"] + [latex_escape(d) for d in datasets]
    rows.append(" & ".join(header) + r" \\")
    rows.append(r"\midrule")
    rows.append(r"\multicolumn{%d}{l}{\emph{FlowCon-X (prototype head)}} \\" % (len(datasets) + 1))
    # Exact experiment names per protocol. A prefix match on "flowconx_" was
    # enough until baseline runs were renamed to flowconx_main_baseline_*:
    # those also match the prefix, carry a `softmax` head rather than
    # `prototype`, and silently replaced this table's headline row with TODO.
    # Prefix matching over an experiment namespace is a trap; name them.
    for split in SPLIT_ORDER:
        cells = []
        for dataset in datasets:
            group = index.get((SPLIT_EXPERIMENT[split], dataset, split))
            cells.append(_cell(group, "prototype") if group else TODO)
        rows.append(f"{SPLIT_LABEL[split]} & " + " & ".join(cells) + r" \\")

    if audit:
        rows.append(r"\midrule")
        rows.append(r"\multicolumn{%d}{l}{\emph{AppScanner (2016), identical splits}} \\" % (len(datasets) + 1))
        for split in SPLIT_ORDER:
            cells = []
            for dataset in datasets:
                entry = (
                    audit.get(dataset, {})
                    .get("splits", {})
                    .get(split, {})
                    .get("baselines", {})
                    .get("appscanner", {})
                )
                value = entry.get("macro_f1")
                if entry.get("status") == "unavailable":
                    cells.append(NOT_APPLICABLE)
                else:
                    cells.append(fmt(value) if isinstance(value, (int, float)) else TODO)
            rows.append(f"{SPLIT_LABEL[split]} & " + " & ".join(cells) + r" \\")

    return table_wrapper(
        "\n".join(rows),
        caption=(
            "Macro-F1 under four split protocols, every method on the identical committed splits. The "
            "random-flow row is the protocol standard in the literature and is reported only as a "
            "contrast: correlated flows from one capture session appear on both sides of it. "
            "\\textbf{The size of that contrast is dataset-dependent}, which is itself the result: on a "
            "corpus of single-session captures a flow's capture is nearly its label, while on a backbone "
            "corpus whose flows are already independent the protocol makes little difference. The caption "
            "deliberately does not assert a direction; read the columns."
        ),
        label="tab:split-contrast",
        columns="l" + "c" * len(datasets),
    )


