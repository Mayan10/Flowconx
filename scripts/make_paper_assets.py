def load_audit(results_root: Path) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    for path in sorted((results_root / "audit").glob("*/audit_summary.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        out[payload["dataset"]] = payload
    return out


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate every paper table and figure.")
    parser.add_argument("--results", default="results")
    parser.add_argument("--out", default="paper")
    parser.add_argument("--datasets", nargs="*", default=["cesnet_quic22", "fiveg_traffic"])
    parser.add_argument("--main-split", default="session_disjoint")
    args = parser.parse_args(argv)

    results_root = Path(args.results)
    out_root = Path(args.out)
    tables_dir = out_root / "tables"
    figures_dir = out_root / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    summary = aggregate(results_root)
    index = _index(summary["groups"])
    audit = load_audit(results_root)
    significance_path = results_root / "significance.json"
    significance = json.loads(significance_path.read_text()) if significance_path.exists() else {}

    written: List[Tuple[Path, int]] = []

    def emit(name: str, content: str) -> None:
        path = tables_dir / name
        path.write_text(content, encoding="utf-8")
        written.append((path, content.count(TODO)))

    emit("split_contrast.tex", table_split_contrast(index, args.datasets, audit))
    for dataset in args.datasets:
        emit(f"main_comparison_{dataset}.tex", table_main_comparison(index, audit, dataset, args.main_split))
    emit("ablation.tex", table_ablations(index, "cesnet_quic22", args.main_split, significance))
    emit("cost.tex", table_cost(index, "cesnet_quic22", args.main_split))
    emit("open_set.tex", table_open_set(results_root))

    figures: List[Optional[Path]] = []
    try:
        figures = [
            figure_early_classification(results_root, figures_dir),
            figure_enrollment(results_root, figures_dir),
            figure_robustness(results_root, figures_dir),
            figure_adversarial_tradeoff(results_root, figures_dir),
        ]
    except ImportError:
        print("matplotlib is not installed; tables written, figures skipped", file=sys.stderr)

    print(f"aggregated {summary['n_runs']} runs into {len(summary['groups'])} groups\n")
    total_todo = 0
    for path, todos in written:
        total_todo += todos
        marker = f"  <- {todos} TODO cell(s)" if todos else ""
        print(f"  {path}{marker}")
    for figure in figures:
        if figure:
            print(f"  {figure}")
    missing_figures = sum(1 for f in figures if f is None)
    if missing_figures:
        print(f"\n  {missing_figures} figure(s) not drawn: the runs behind them have not happened yet.")
    if total_todo:
        print(
            f"\n{total_todo} TODO cell(s) remain. Each is a run that has not happened. "
            "They are never filled with a plausible value."
        )
    else:
        print("\nEvery cell is populated from a run.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
