# Only the rows that were run. The component and hyperparameter sweeps were
# cut deliberately -- see ABLATIONS_CUT in scripts/run_all_experiments.py and
# paper/RESULTS.md -- and the caption declares the table partial rather than
# letting missing rows read as uninteresting ones.
ABLATION_ROWS = [
    ("ablation_full", "Full model"),
    ("ablation_classify_z_app", r"classify from $z_{\mathrm{app}}$"),
    ("ablation_classify_z_network", r"classify from $z_{\mathrm{net}}$"),
    ("ablation_classify_z_concat", r"classify from $z_{\mathrm{app}} \| z_{\mathrm{net}}$"),
    ("ablation_no_adversarial", r"$-$ adversarial nuisance removal"),
    ("ablation_adv_weight_0p0", r"$\lambda_{\mathrm{adv}} = 0$"),
    ("ablation_adv_weight_0p01", r"$\lambda_{\mathrm{adv}} = 0.01$"),
    ("ablation_adv_weight_0p1", r"$\lambda_{\mathrm{adv}} = 0.1$"),
    ("ablation_adv_weight_0p5", r"$\lambda_{\mathrm{adv}} = 0.5$"),
    ("ablation_adv_weight_1p0", r"$\lambda_{\mathrm{adv}} = 1.0$"),
]


def table_ablations(index, dataset: str, split: str, significance: Dict[str, Any]) -> str:
    rows: List[str] = [r"Variant & Macro-F1 & $\Delta$ & $p$ & Params \\", r"\midrule"]
    reference = index.get(("ablation_full", dataset, split)) or index.get(("flowconx_main", dataset, split))
    reference_mean = (reference or {}).get("heads", {}).get("prototype", {}).get("macro_f1", {}).get("mean")
    lookup = _significance_lookup(significance)

    for experiment, label in ABLATION_ROWS:
        group = index.get((experiment, dataset, split))
        if group is None and experiment == "ablation_full":
            group = reference
        if group is None:
            rows.append(f"{label} & {TODO} & {TODO} & {TODO} & {TODO} \\\\")
            continue
        stats = group.get("heads", {}).get("prototype", {}).get("macro_f1", {})
        mean = stats.get("mean")
        delta = (
            f"{mean - reference_mean:+.3f}"
            if mean is not None and reference_mean is not None and experiment != "ablation_full"
            else "---"
        )
        entry = lookup.get((experiment, dataset, split))
        if entry is None:
            p_cell = NOT_APPLICABLE if experiment == "ablation_full" else TODO
        else:
            correction = entry.get("correction", {})
            p_value = entry.get("p_value")
            if p_value is not None and np.isfinite(p_value):
                marker = r"$^{*}$" if correction.get("significant") else ""
                p_cell = f"{p_value:.3g}{marker}"
            elif correction.get("undetermined"):
                # The test ran and declined: too few seeds for it to have power.
                # Rendering this as TODO would claim the run had not happened.
                p_cell = UNDETERMINED
            else:
                p_cell = TODO
        params = group.get("extras", {}).get("n_parameters", {}).get("mean")
        params_cell = f"{int(params):,}".replace(",", r"\,") if params else TODO
        rows.append(f"{label} & {fmt(mean, stats.get('std'))} & {delta} & {p_cell} & {params_cell} \\\\")

    return table_wrapper(
        "\n".join(rows),
        caption=(
            "\\textbf{Partial ablation family.} Embedding choice and the adversarial weight sweep, at "
            "the reduced ablation budget (10 epochs on a seeded stratified 72{,}000-row subsample), "
            "mean $\\pm$ std over seeds. $\\Delta$ is the change in macro-F1 against the full model. "
            "$p$ is a Wilcoxon signed-rank test across seeds, Holm-Bonferroni corrected within this "
            "family; $^{*}$ marks comparisons surviving the correction at $\\alpha = 0.05$, and "
            "\\emph{n.d.} marks comparisons the test declined to make --- at three seeds its minimum "
            "achievable $p$-value is $0.25$, so it has no power at any effect size. Those rows are "
            "reported with effect sizes and seed spreads instead, and are not claimed as significant. "
            "The fusion variants, loss-term ablations, and temperature, margin and input-budget sweeps "
            "were \\emph{not run}: they were designed to explain why the model wins the closed-set "
            "comparison, and it does not win it. See \\texttt{paper/RESULTS.md} for the full list of "
            "omitted configurations and the command that would run them."
        ),
        label="tab:ablation",
        columns="lcccc",
    )


def _significance_lookup(significance: Dict[str, Any]) -> Dict[Tuple[str, str, str], Dict[str, Any]]:
    out: Dict[Tuple[str, str, str], Dict[str, Any]] = {}
    for family in significance.get("families", []):
        for comparison in family.get("comparisons", []):
            key = (comparison.get("experiment"), comparison.get("dataset"), comparison.get("split"))
            if all(key):
                out[key] = comparison
    return out


